const messages: Record<
  ApplicationLanguage,
  Record<InterfaceMessageKey, string>
> = {
  "zh-CN": zhMessages,
  "en-US": enMessages,
};

export function normalizeApplicationLanguage(
  value: unknown,
): ApplicationLanguage {
  return value === "en-US" ? "en-US" : defaultApplicationLanguage;
}

export function readApplicationLanguage(
  storage: LanguageStorage | null = browserStorage(),
): ApplicationLanguage {
  if (!storage) return defaultApplicationLanguage;
  try {
    return normalizeApplicationLanguage(
      storage.getItem(applicationLanguageStorageKey),
    );
  } catch {
    return defaultApplicationLanguage;
  }
}

export function writeApplicationLanguage(
  language: ApplicationLanguage,
  storage: LanguageStorage | null = browserStorage(),
): void {
  if (!storage) return;
  try {
    storage.setItem(applicationLanguageStorageKey, language);
  } catch {
    // The in-memory setting remains active when storage is unavailable.
  }
}

export function interfaceMessage(
  language: ApplicationLanguage,
  key: InterfaceMessageKey,
): string {
  return messages[language][key];
}

function browserStorage(): Storage | null {
  if (typeof window === "undefined") return null;
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}
